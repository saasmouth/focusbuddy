import { registerWidgetContextActions } from './registry'
import { useWidgetStore } from '../../stores/widgets'
import { effectiveLayout, SECTION_PADDING } from '../sectionGeometry'
import { DUPLICATE_EMPTY_LABEL } from './labels'
import { useWidgetSetup } from '../../stores/widgetSetup'
import { useTablesStore } from '../../stores/tables'
import { createConnectedTool } from '../createConnectedTool'
import { hasChecklist, toggleChecklist } from '../stickyText'

// "Build with AI" drafts a list of items to add in the widget's own format and
// lets the user approve them (the tables-style AI setup, generalised). Offered
// on the widget kinds the main-process generator supports (sticky, note,
// markdown, card).
function buildWithAiRow(widgetId: string): MenuContribution {
  return {
    id: 'core/build-with-ai',
    group: 'object',
    priority: -1, // sits at the very top of the context band
    label: 'Build with AI',
    icon: 'auto_awesome',
    onSelect: () => useWidgetSetup.getState().start(widgetId)
  }
}

// Sticky: a real widget-specific action that proves the registration path end
// to end. Toggling the checklist is a pure transform on the sticky's text, so
// it is safe to drive from the menu.
registerWidgetContextActions('sticky', (ctx) => {
  if (ctx.object.type !== 'widget') return { context: [] }
  const w = ctx.object.widget
  const checklist = hasChecklist(w.content || '')
  return {
    context: [
      buildWithAiRow(w.id),
      {
        id: 'sticky/checklist',
        group: 'object',
        priority: 0,
        label: checklist ? 'Remove checkboxes' : 'Make a checklist',
        icon: 'checklist',
        onSelect: () => void useWidgetStore.getState().update(w.id, { content: toggleChecklist(w.content || '') })
      }
    ]
  }
})

// The remaining widgets the generator supports get Build with AI as their
// context action. Mindmap drafts branches; diagram drafts nodes.
for (const kind of ['note', 'markdown', 'card', 'mindmap', 'diagram'] as const) {
  registerWidgetContextActions(kind, (ctx) => {
    if (ctx.object.type !== 'widget') return { context: [] }
    return { context: [buildWithAiRow(ctx.object.widget.id)] }
  })
}

// Living Doc: the document is regenerated by AI, so manual AI Assist rewrites of
// the body would be overwritten on the next cycle. Suppress AI Assist there and
// offer a regenerate-now action in the Context band instead.
registerWidgetContextActions('living-doc', (ctx) => {
  if (ctx.object.type !== 'widget') return { context: [] }
  const w = ctx.object.widget
  return {
    context: [
      {
        id: 'living-doc/regenerate',
        group: 'object',
        priority: 0,
        label: 'Regenerate now',
        icon: 'autorenew',
        onSelect: () => void window.api.livingPage.regenerate(w.id)
      }
    ],
    suppress: { 'ai-assist': true }
  }
})

// Table: "Add row" applies anywhere on the table (header or a cell), so it is a
// wildcard. The cell provider below adds the row-specific actions that need to
// know WHICH row was clicked.
registerWidgetContextActions('table', (ctx) => {
  if (ctx.object.type !== 'widget') return { context: [] }
  const tableId = ctx.object.widget.content
  return {
    context: [
      {
        id: 'table/add-row',
        group: 'object',
        priority: 0,
        label: 'Add row',
        icon: 'add',
        onSelect: () => void useTablesStore.getState().addRow(tableId)
      }
    ]
  }
})

// Table cell: row-specific actions on the cell that was right-clicked, plus the
// universal sections seeded from the cell text (Create a sticky from this cell,
// AI Assist on the cell, ...). Operates through the tables store directly.
registerWidgetContextActions('table', 'cell', (ctx) => {
  if (ctx.object.type !== 'widget') return { context: [] }
  const tableId = (ctx.sub?.payload?.tableId as string) || ctx.object.widget.content
  const rowId = ctx.sub?.payload?.rowId as string | undefined
  if (!rowId) return { context: [] }
  return {
    context: [
      {
        id: 'table/duplicate-row',
        group: 'object',
        priority: 1,
        label: 'Duplicate row',
        icon: 'content_copy',
        onSelect: () => {
          const store = useTablesStore.getState()
          const tableRows = store.rows[tableId] ?? []
          const src = tableRows.find((r) => r.id === rowId)
          void store.addRow(tableId, src ? { ...src.cells } : {})
        }
      },
      {
        // A row is content inside the table: Delete, in the destructive group
        // (danger routes it there; F-11 found it buried in the Context band).
        id: 'table/delete-row',
        group: 'destructive',
        priority: -10, // the clicked row first, before the rows that remove the whole widget
        label: 'Delete row',
        icon: 'delete',
        danger: true,
        onSelect: () => void useTablesStore.getState().deleteRow(rowId)
      }
    ]
  }
})

// Link / file widgets: their content is a URL or file path, so offer Open and
// Copy. Covers files, images, video, PDFs, the Google document kinds, email,
// and the browser widget's own address.
const LINK_KINDS = ['file', 'image', 'video', 'pdf', 'gdoc', 'gsheet', 'gslide', 'email', 'webview'] as const
for (const kind of LINK_KINDS) {
  registerWidgetContextActions(kind, (ctx) => {
    if (ctx.object.type !== 'widget') return { context: [] }
    const url = (ctx.object.widget.content || '').trim()
    if (!url) return { context: [] }
    const isHttp = /^https?:\/\//i.test(url)
    return {
      context: [
        {
          id: `${kind}/open-external`,
          opens: true,
          group: 'object',
          priority: 0,
          label: isHttp ? 'Open in browser' : MENU.open.label,
          icon: 'open_in_new',
          onSelect: () => void window.api.files.openExternal(url)
        },
        {
          id: `${kind}/copy-url`,
          group: 'clipboard',
          priority: 15,
          label: isHttp ? MENU.copyLink.label : 'Copy path',
          icon: 'content_copy',
          onSelect: () => {
            void navigator.clipboard.writeText(url).catch(() => {})
          }
        }
      ]
    }
  })
}


// Aggregate the eval runs into a table, and derive the quality gates for the
// chosen on-device model.
//
//   node tools/local-ai-eval/report.mjs --chosen <run label> [--reference cloud-claude]
//
// Reads results/run-*.json and results/bench-*.json. Writes:
//   results/summary.md   per-family pass rates for every run, latency, bench
//   results/gates.json   the gates src/shared/localAiGates.ts must equal
//
// A task passes when its deterministic checks pass AND (when it has a rubric)
// the judge scored it 4 or 5. Every number printed is computed from the run
// files; nothing is entered by hand.
//
// Gate rule, per app feature, from the chosen model's pass rate L and the
// cloud reference's C on the feature's eval families:
//   ok          L >= 0.85 * C   — runs on the device, no caveat
//   labelled    L >= 0.50 * C   — runs on the device with "works best with cloud AI"
//   cloud-only  otherwise, or not measured — not attempted on the device; the
//               user is asked whether to send that one request to cloud
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), 'results')
const args = process.argv.slice(2)
const opt = (n, d) => {
  const i = args.indexOf(`--${n}`)
  return i >= 0 ? args[i + 1] : d
}
const chosen = opt('chosen', null)
const reference = opt('reference', 'cloud-claude')

const FAMILIES = ['desk_qa', 'proposals', 'brain_qa', 'refusal', 'writing', 'summaries', 'build', 'office', 'background']
// App feature → the eval families that measure it (src/shared/localAi.ts).
export const FEATURE_FAMILIES = {
  assistant: ['desk_qa', 'proposals', 'brain_qa', 'refusal'],
  build: ['build'],
  office: ['office'],
  writing: ['writing'],
  summaries: ['summaries'],
  background: ['background'],
  agents: [],
  // No language model: image generation and background removal have no
  // on-device equivalent at all.
  media: []
}

const runs = readdirSync(dir)
  .filter((f) => /^run-.+\.json$/.test(f))
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
const benches = readdirSync(dir)
  .filter((f) => /^bench-.+\.json$/.test(f))
  .map((f) => ({ file: f, ...JSON.parse(readFileSync(join(dir, f), 'utf8')) }))

function famStats(run, fams) {
  const rs = run.results.filter((r) => fams.includes(r.family))
  const passed = rs.filter((r) => r.passed).length
  const ms = rs.map((r) => r.ms).sort((a, b) => a - b)
  return { n: rs.length, passed, rate: rs.length ? passed / rs.length : null, medianMs: ms.length ? ms[Math.floor(ms.length / 2)] : null }
}
const fmtRate = (s) => (s.n ? `${s.passed}/${s.n} (${Math.round((s.passed / s.n) * 100)}%)` : 'n/a')
const fmtS = (ms) => (ms === null ? '' : `${(ms / 1000).toFixed(1)} s`)

const ordered = [...runs].sort((a, b) => (a.label === reference ? 1 : b.label === reference ? -1 : a.label.localeCompare(b.label)))
const lines = []
lines.push('# Local AI eval — results')
lines.push('')
lines.push(`Generated by tools/local-ai-eval/report.mjs from ${runs.length} run file(s). A task passes when its deterministic checks pass and, if it has a rubric, the judge (${runs.find((r) => r.judge)?.judge?.model ?? 'n/a'}) scores it ≥ ${runs.find((r) => r.judge)?.judge?.passScore ?? 4}/5.`)
lines.push('')
lines.push('## Pass rate by task family')
lines.push('')
lines.push(`| family | ${ordered.map((r) => r.label).join(' | ')} |`)
lines.push(`| --- | ${ordered.map(() => '---').join(' | ')} |`)
for (const f of FAMILIES) lines.push(`| ${f} | ${ordered.map((r) => fmtRate(famStats(r, [f]))).join(' | ')} |`)
lines.push(`| **all** | ${ordered.map((r) => `**${fmtRate(famStats(r, FAMILIES))}**`).join(' | ')} |`)
lines.push('')
lines.push('## Median wall time per task (includes prompt processing and generation)')
lines.push('')
lines.push(`| family | ${ordered.map((r) => r.label).join(' | ')} |`)
lines.push(`| --- | ${ordered.map(() => '---').join(' | ')} |`)
for (const f of FAMILIES) lines.push(`| ${f} | ${ordered.map((r) => fmtS(famStats(r, [f]).medianMs)).join(' | ')} |`)
lines.push('')
const localRuns = ordered.filter((r) => r.results.some((x) => x.engine))
if (localRuns.length) {
  lines.push('## Prompt size seen by the on-device engine (median input tokens per task)')
  lines.push('')
  lines.push(`| family | ${localRuns.map((r) => r.label).join(' | ')} |`)
  lines.push(`| --- | ${localRuns.map(() => '---').join(' | ')} |`)
  for (const f of FAMILIES) {
    lines.push(
      `| ${f} | ${localRuns
        .map((r) => {
          const v = r.results.filter((x) => x.family === f && x.engine).map((x) => x.engine.input).sort((a, b) => a - b)
          return v.length ? String(v[Math.floor(v.length / 2)]) : ''
        })
        .join(' | ')} |`
    )
  }
  lines.push('')
}
lines.push('## Network during generation')
lines.push('')
for (const r of ordered) {
  const hosts = [...new Set(r.egress.map((e) => e.split('/')[0]))]
  lines.push(`- ${r.label} (${r.target}): ${r.egress.length} request(s)${hosts.length ? ` to ${hosts.join(', ')}` : ''}; blocked by the guard: ${r.blocked.length}`)
}
lines.push('')
if (benches.length) {
  lines.push('## Engine benchmark (bench.mjs, this machine)')
  lines.push('')
  lines.push('| model | disk | load | prefill tok/s | TTFT after ~6k-token prompt | follow-up TTFT | gen tok/s | RSS after load | GPU-visible memory |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const b of benches) {
    const t = b.timings
    lines.push(
      `| ${b.model} | ${(b.diskBytes / 1e9).toFixed(2)} GB | ${(t.loadMs / 1000).toFixed(1)} s | ${t.prefillTokPerSec} | ${(t.prefillTtftMs / 1000).toFixed(1)} s | ${(t.followupTtftMs / 1000).toFixed(2)} s | ${t.genTokPerSec} | ${b.memory.rssAfterLoadMB} MB | ${b.memory.gpuUsedAfterLoadMB} MB |`
    )
  }
  lines.push('')
}
lines.push('## Failures per run')
lines.push('')
for (const r of ordered) {
  lines.push(`### ${r.label}`)
  for (const x of r.results.filter((x) => !x.passed)) {
    const why = !x.checksPassed
      ? 'checks: ' + x.checks.filter((c) => !c.ok).map((c) => `${c.name}${c.detail ? ` (${String(c.detail).slice(0, 80)})` : ''}`).join('; ')
      : `judge ${x.verdict?.score}/5: ${String(x.verdict?.reason ?? '').slice(0, 220)}`
    lines.push(`- ${x.id}: ${why}`)
  }
  lines.push('')
}

let gates = null
if (chosen) {
  const L = runs.find((r) => r.label === chosen)
  const C = runs.find((r) => r.label === reference)
  if (!L || !C) throw new Error(`need run files for ${chosen} and ${reference}`)
  gates = { chosen, reference, rule: 'ok >= 0.85*cloud; labelled >= 0.50*cloud; else cloud-only; unmeasured → cloud-only', features: {} }
  lines.push(`## Gates for ${chosen} (vs ${reference})`)
  lines.push('')
  lines.push('| feature | families | local | cloud | gate |')
  lines.push('| --- | --- | --- | --- | --- |')
  for (const [feature, fams] of Object.entries(FEATURE_FAMILIES)) {
    const l = famStats(L, fams)
    const c = famStats(C, fams)
    let gate = 'cloud-only'
    if (l.rate !== null && c.rate) {
      if (l.rate >= 0.85 * c.rate) gate = 'ok'
      else if (l.rate >= 0.5 * c.rate) gate = 'labelled'
    }
    gates.features[feature] = {
      families: fams,
      local: l.rate === null ? null : +l.rate.toFixed(3),
      cloud: c.rate === null ? null : +c.rate.toFixed(3),
      gate
    }
    lines.push(`| ${feature} | ${fams.join(', ') || '(not measured)'} | ${fmtRate(l)} | ${fmtRate(c)} | ${gate} |`)
  }
  lines.push('')
  writeFileSync(join(dir, 'gates.json'), JSON.stringify(gates, null, 2) + '\n')
}

writeFileSync(join(dir, 'summary.md'), lines.join('\n') + '\n')
console.log(lines.join('\n'))

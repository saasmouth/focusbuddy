// Derive the renderer's api-path -> IPC-channel map from the preload itself.
//
// The cloud runtime has to answer the same calls the preload does, and the two
// namings do not line up: window.api.workspaceSync.pending is 'workspace:pending',
// and there are enough of those to make a naming convention a guess rather than
// a rule. Reading the preload makes the map exact, and regenerating it means a
// channel renamed on the desktop cannot silently stop working in the browser.
//
// Emits src/web/api/channelMap.generated.ts. Run: node scripts/derive-web-channel-map.cjs
const fs = require('fs')

const SRC = 'src/preload/index.ts'
const OUT = 'src/web/api/channelMap.generated.ts'

const text = fs.readFileSync(SRC, 'utf8')
const lines = text.split('\n')

const invokes = {}   // "ns.method" -> channel
const listeners = {} // "ns.method" -> channel (ipcRenderer.on subscriptions)
let ns = null

for (const line of lines) {
  // Namespace opener: exactly two spaces of indent, then `name: {`
  const open = /^ {2}([a-zA-Z][a-zA-Z0-9_]*): \{/.exec(line)
  if (open) { ns = open[1]; continue }
  if (/^ {2}\},?$/.test(line)) { ns = null; continue }
  if (!ns) continue

  const member = /^\s{4}([a-zA-Z][a-zA-Z0-9_]*)\s*:/.exec(line)
  const invoke = /ipcRenderer\.invoke\(\s*'([^']+)'/.exec(line)
  const on = /ipcRenderer\.on\(\s*'([^']+)'/.exec(line)
  if (member && invoke) invokes[`${ns}.${member[1]}`] = invoke[1]
  else if (member && on) listeners[`${ns}.${member[1]}`] = on[1]
}

// A member whose invoke sits on a later line than its name (multi-line arrow
// bodies) is picked up by a second pass that pairs the nearest preceding member.
let pending = null
for (const line of lines) {
  const open = /^ {2}([a-zA-Z][a-zA-Z0-9_]*): \{/.exec(line)
  if (open) { ns = open[1]; pending = null; continue }
  if (/^ {2}\},?$/.test(line)) { ns = null; pending = null; continue }
  if (!ns) continue
  const member = /^\s{4}([a-zA-Z][a-zA-Z0-9_]*)\s*:/.exec(line)
  if (member) { pending = `${ns}.${member[1]}`; continue }
  if (!pending) continue
  const invoke = /ipcRenderer\.invoke\(\s*'([^']+)'/.exec(line)
  const on = /ipcRenderer\.on\(\s*'([^']+)'/.exec(line)
  if (invoke && !invokes[pending]) invokes[pending] = invoke[1]
  else if (on && !listeners[pending] && !invokes[pending]) listeners[pending] = on[1]
  if (invoke || on) pending = null
}

const entries = (o) => Object.keys(o).sort().map((k) => `  '${k}': '${o[k]}'`).join(',\n')

const out = `// GENERATED by scripts/derive-web-channel-map.cjs -- do not edit.
//
// window.api path -> IPC channel, read out of the preload so the cloud runtime
// and the desktop cannot drift on what a call is named.

/** Request/response calls: api.<path>(...args) -> invoke(channel, ...args). */
export const INVOKE_CHANNELS: Readonly<Record<string, string>> = {
${entries(invokes)}
}

/** Subscriptions: api.<path>(cb) -> main-process pushes on channel. */
export const LISTEN_CHANNELS: Readonly<Record<string, string>> = {
${entries(listeners)}
}
`
fs.mkdirSync('src/web/api', { recursive: true })
fs.writeFileSync(OUT, out)
console.log(`  ${Object.keys(invokes).length} invoke channels, ${Object.keys(listeners).length} subscriptions -> ${OUT}`)
